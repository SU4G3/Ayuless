"""Bootstrap QuickJS's builtins from JS, without trusting precompiled bytecode."""
import argparse
import json
import os
from pathlib import Path
import shlex
import subprocess


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    source = root / "TMessagesProj/jni/twidget/widget-sandbox/packages/ios/Sources/CQuickJS/quickjs"
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    engine = (source / "quickjs.c").read_text()
    bootstrap = engine
    for name in ("array-fromasync", "iterator-zip-keyed", "iterator-zip"):
        stem = "builtin-" + name
        # JS_Eval requires a terminating NUL; sizeof below must exclude it.
        text = (source / (stem + ".js")).read_text()
        symbol = "qjsc_" + stem.replace("-", "_")
        literal = json.dumps(text, ensure_ascii=False)
        assert bootstrap.count('#include "' + stem + '.h"') == 1, "QuickJS builtin include changed"
        bootstrap = bootstrap.replace(
            '#include "' + stem + '.h"',
            "static const uint8_t " + symbol + "[] = " + literal + ";",
        )
        bootstrap = bootstrap.replace("sizeof(" + symbol + ")", "sizeof(" + symbol + ") - 1")
    old = "obj = JS_ReadObject(ctx, bytecode, len, JS_READ_OBJ_BYTECODE);"
    assert bootstrap.count(old) == 1, "QuickJS bootstrap hook changed"
    bootstrap = bootstrap.replace(
        old,
        'obj = JS_Eval(ctx, (const char *)bytecode, len, "<builtin>", '
        "JS_EVAL_TYPE_GLOBAL | JS_EVAL_FLAG_COMPILE_ONLY);",
    )
    # Only the host bootstrap uses source evaluation. The shipped engine stays
    # byte-for-byte unchanged and uses headers regenerated by that compiler.
    (output / "quickjs-bootstrap.c").write_text(bootstrap)
    compiler = shlex.split(os.environ.get("HOST_CC", "cc"))
    command = compiler + [
        "-O2", "-g0", "-fno-ident", "-fno-strict-aliasing", "-std=gnu11",
        "-D_GNU_SOURCE", "-DQUICKJS_NG_BUILD", "-Wno-unused-parameter",
        f"-ffile-prefix-map={root}=/src", f"-ffile-prefix-map={output}=/quickjs-host",
        "-I", str(source), str(output / "quickjs-bootstrap.c"),
    ]
    command += [str(source / name) for name in
                ("dtoa.c", "libregexp.c", "libunicode.c", "quickjs-libc.c", "qjsc.c")]
    command += ["-lm", "-ldl", "-pthread", "-o", str(output / "qjsc")]
    subprocess.run(command, check=True)
    for path in sorted(source.glob("builtin-*.js")):
        subprocess.run([str(output / "qjsc"), "-C", "-ss", "-o",
                        str(output / (path.stem + ".h")), path.name],
                       cwd=source, check=True)
    (output / "quickjs.c").write_text(engine)


if __name__ == "__main__":
    main()
